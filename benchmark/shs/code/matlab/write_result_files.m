function write_result_files(out_dir, recurrence, set_name, pts, out, meta)
%WRITE_RESULT_FILES Write results/graflab_<recurrence>_<set>.csv and its .md companion.
%   Header: id,lat_deg,lon_deg,h_m,V_m2s2,T_m2s2,dg_mgal
%   15 significant digits. Coordinates are copied from the input points file; the values come from GrafLab,
%   where out(:,4) is V (Functional 11), out(:,5) is T (Functional 5) and out(:,6) is dg (Functional 20, mGal).

base = sprintf('graflab_%s_%s', recurrence, set_name);
csv_path = fullfile(out_dir, [base '.csv']);
md_path = fullfile(out_dir, [base '.md']);

fid = fopen(csv_path, 'w');
if fid < 0
    error('write_result_files:open', 'Cannot write %s', csv_path);
end
fprintf(fid, 'id,lat_deg,lon_deg,h_m,V_m2s2,T_m2s2,dg_mgal\n');
for i = 1:numel(pts.lat)
    fprintf(fid, '%s,%.15g,%.15g,%.15g,%.15g,%.15g,%.15g\n', pts.id{i}, pts.lat(i), pts.lon(i), ...
        pts.h(i), out(i, 4), out(i, 5), out(i, 6));
end
fclose(fid);

fid = fopen(md_path, 'w');
if fid < 0
    error('write_result_files:open', 'Cannot write %s', md_path);
end
cleaner = onCleanup(@() fclose(fid));

fprintf(fid, '# GrafLab 2.1.4: %s, %s\n\n', recurrence, set_name);
fprintf(fid, 'Generated by `code/matlab/run_graflab.m` (MATLAB %s) on %s. V, T and dg come from one GrafLab call per repetition.\n\n', ...
    meta.matlab_release, datestr(now, 'yyyy-mm-dd HH:MM')); %#ok<DATST>

fprintf(fid, '## Exact command\n\n```\nmatlab -batch "%s"\n```\n\n', meta.command);
fprintf(fid, 'Run from `benchmark/shs/code/matlab`, with GrafLab.m supplied by the user (not redistributed).\n\n');

fprintf(fid, '## Columns\n\n');
fprintf(fid, '| column | unit | meaning |\n|---|---|---|\n');
fprintf(fid, '| id | - | point id copied from the input CSV |\n');
fprintf(fid, '| lat_deg | deg | geodetic latitude on GRS80, copied from the input CSV |\n');
fprintf(fid, '| lon_deg | deg | longitude, copied from the input CSV |\n');
fprintf(fid, '| h_m | m | ellipsoidal height on GRS80, copied from the input CSV |\n');
fprintf(fid, '| V_m2s2 | m^2 s^-2 | gravitational potential V of the model (GrafLab functional 11), full double precision from GrafLab; no normal potential subtracted, degree 0 included with C00 of the file |\n');
fprintf(fid, '| T_m2s2 | m^2 s^-2 | disturbing potential T = V - U (GrafLab functional 5), full double precision from GrafLab |\n');
fprintf(fid, '| dg_mgal | mGal | gravity disturbance, full magnitudes, not spherical approximation (GrafLab functional 20) |\n\n');

fprintf(fid, '## GrafLab parameters used\n\n');
fprintf(fid, '| parameter | value |\n|---|---|\n');
fprintf(fid, '| GrafLab | 2.1.4 (GrafLab.m, Bucha and Janak 2013), headless call `GrafLab(''OK'', ...)` |\n');
fprintf(fid, '| model file | `%s` |\n', meta.gfc_name);
fprintf(fid, '| product_type / tide_system in header | %s / %s (GrafLab does not check tide_system; no conversion applied) |\n', ...
    meta.product_type, meta.tide_system);
fprintf(fid, '| GM, R (from .gfc header, used by GrafLab) | %.10g m^3 s^-2, %.10g m |\n', meta.GM, meta.R);
fprintf(fid, '| reference ellipsoid | GRS80 (`ellipsoid = 1`): GM 3.986005e14, a 6378137 m, e^2 0.006694380022903416, omega 7292115e-11 |\n');
fprintf(fid, '| coordinates | ellipsoidal (`coord = 0`) |\n');
fprintf(fid, '| point type | point-wise (`point_type = 2`): arrays lat, lon, h2 passed directly |\n');
fprintf(fid, '| nmin, nmax | 0, %d |\n', meta.nmax);
fprintf(fid, '| Legendre recurrence | `fnALFs = %d` (%s) |\n', meta.fnALFs, recurrence_text(recurrence));
fprintf(fid, '| functionals | `Functional = [11; 5; 20]` (V, T, dg in one call), `Functional_or_Commission = 0` |\n');
fprintf(fid, '| exports | none (`Export_data_txt = Export_report = Export_data_mat = 0`); matrix returned by `nargout == 1` |\n');
fprintf(fid, '| points | %d from `%s` |\n\n', numel(pts.lat), meta.points_name);

fprintf(fid, '## Limitations of GrafLab found for this benchmark\n\n');
fprintf(fid, '- Point evaluation is supported natively (point-wise mode). No grid, no interpolation and no node selection were used.\n');
fprintf(fid, '- Only ellipsoidal coordinates were used. Spherical input (`coord = 1`) was not needed.\n');
fprintf(fid, '- V (functional 11) is taken by GrafLab from the coefficients of the file (its `grav` branch uses C, not the disturbing coefficients). No normal potential is subtracted and no delta C00 term is added: degree 0 is C00 of the file.\n');
fprintf(fid, '- dg (functional 20) cannot be computed with `nmin > 0`, so `nmin = 0` is used. T then includes the degree-zero term Delta C00 = (GM - GM_Ell)/GM, which is the consistent V - U with GM of the model and GRS80 normal potential (as documented in Bucha and Janák 2019).\n');
fprintf(fid, '- The columns of the output follow the order of the Functional vector [11; 5; 20]: V, T, dg.\n');
fprintf(fid, '- GrafLab takes GM and R from the .gfc header and ignores the values passed in the call (it only warns if they differ). The header values are passed anyway.\n');
fprintf(fid, '- The .gfc reader only checks `norm fully_normalized` and the 7-column layout. It ignores `tide_system`. The tide-free file is used as given.\n');
fprintf(fid, '- Model load is repeated on every GrafLab call (the .gfc is parsed with textscan). Synthesis time is therefore obtained by subtraction, see below.\n');
fprintf(fid, '- GrafLab text export writes 13 significant digits. This CSV does not use it: the matrix returned in memory (full double) is used.\n');
fprintf(fid, '- The GUI-free path still calls `set`/`findobj` on the GUI tags; they are no-ops without a figure.\n\n');

fprintf(fid, '## Timing and reproducibility\n\n');
fprintf(fid, '- Model load (1-point call through the same pipeline): load_s = %.3f s (cpu %.3f s).\n', meta.load_s, meta.load_cpu_s);
fprintf(fid, '- Synthesis wall time = total call wall time - load_s. Rows appended to `results/timings.csv` (notes: functional=V_T_dg).\n');
fprintf(fid, '- The subtraction is only meaningful when synthesis dominates the call. For small runs (few points, low nmax) the synthesis part is at the noise level of the load probe (about +-0.3 s here, negative values possible). Check the numbers in this run: load_s = %.3f s.\n', meta.load_s);
fprintf(fid, '- MATLAB computational threads: %d. cputime is process CPU time.\n', meta.threads);
fprintf(fid, '- Repetitions: %d. Max abs difference of repetitions 2..n against repetition 1 (V, T, dg): ', meta.repeat_count);
if meta.repeat_count > 1
    fprintf(fid, '%s\n\n', mat2str(max(meta.max_diff(2:end, :), [], 1), 6));
else
    fprintf(fid, 'not applicable.\n\n');
end
end

function txt = recurrence_text(recurrence)
switch recurrence
    case 'sfc'
        txt = 'standard forward column method';
    case 'msfc'
        txt = 'modified forward column method';
    case 'era'
        txt = 'extended-range arithmetic';
    otherwise
        txt = 'unknown';
end
end
